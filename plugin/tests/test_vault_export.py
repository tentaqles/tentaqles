"""The Markdown mirror: memory.db rendered as Obsidian notes, one folder per client.

context.md, decisions.md, plan.md and fixes.md are rewritten on every export;
sessions/ gets one note per ended session and existing ones are left alone.
Every note starts with YAML frontmatter (type, client, status, updated) so
Obsidian Bases can filter on it, and a generated-by marker so nobody edits a
file the next export will overwrite.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
import yaml

from tentaqles.knowledge import KnowledgeConfig
from tentaqles.memory.store import MemoryStore
from tentaqles.memory.vault_export import export_workspace

MANIFEST = {
    "client": "acme",
    "display_name": "Acme Corp",
    "stack": ["python", "postgres"],
    "cloud": {"provider": "azure", "subscription_name": "acme-prod"},
    "database": {"provider": "supabase"},
    "git": {"host": "github", "user": "acme-bot", "email": "bot@acme.test"},
}


@pytest.fixture
def store(tmp_path, monkeypatch):
    monkeypatch.setattr(MemoryStore, "_embed", lambda self, text: None)
    s = MemoryStore(tmp_path / "ws")
    yield s
    s.close()


def _cfg(tmp_path, **kw) -> KnowledgeConfig:
    return KnowledgeConfig(vault_dir=tmp_path / "vault", **kw)


def _frontmatter(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    assert text.startswith("---\n"), path
    _, fm, body = re.split(r"^---\s*$", text, maxsplit=2, flags=re.MULTILINE)
    return yaml.safe_load(fm), body


def _populate(store):
    store.start_session()
    store.touch("src/app/parser.py", action="edit")
    store.touch("src/app/parser.py", action="edit")
    store.touch("README.md", action="read")
    d_old = store.record_decision("Use Postgres", "ACID", rejected=["Mongo"], confidence="high")
    d_new = store.record_decision("Retry webhooks from a queue", "inline retries blocked requests")
    p_hi = store.add_pending("Rotate the signing certificate", priority="high")
    p_lo = store.add_pending("Tidy the README", priority="low")
    store.record_tool_failure("pytest", "ModuleNotFoundError: No module named 'yaml'")
    store.record_tool_success("pip install pyyaml && pytest")
    store.end_session("Refactored the invoice exporter and fixed CSV quoting")
    return d_old, d_new, p_hi, p_lo


def test_export_writes_one_folder_per_client_with_the_four_notes(store, tmp_path):
    _populate(store)

    written = export_workspace(store, MANIFEST, _cfg(tmp_path))

    client_dir = tmp_path / "vault" / "acme"
    names = {p.relative_to(client_dir).as_posix() for p in written}
    assert {"context.md", "decisions.md", "plan.md", "fixes.md"} <= names
    assert any(n.startswith("sessions/") and n.endswith(".md") for n in names)
    assert all(p.exists() for p in written)


def test_every_note_has_frontmatter_and_a_generated_marker(store, tmp_path):
    _populate(store)
    for path in export_workspace(store, MANIFEST, _cfg(tmp_path)):
        fm, body = _frontmatter(path)
        assert fm["client"] == "acme"
        assert fm["generated_by"] == "tentaqles"
        assert fm["type"] in {"context", "decisions", "plan", "fixes", "session"}
        assert "status" in fm and "updated" in fm
        assert "generated by tentaqles" in body.splitlines()[1].lower() or "generated by tentaqles" in body.lower()


def test_decisions_are_active_only_newest_first_with_rationale(store, tmp_path):
    d_old, d_new, *_ = _populate(store)
    store.supersede_decision(d_old, "Use Postgres with pgbouncer", "connection limits")

    export_workspace(store, MANIFEST, _cfg(tmp_path))

    fm, body = _frontmatter(tmp_path / "vault" / "acme" / "decisions.md")
    assert fm["type"] == "decisions" and fm["status"] == "confirmed"
    assert "Use Postgres with pgbouncer" in body and "connection limits" in body
    assert body.index("Use Postgres with pgbouncer") < body.index("Retry webhooks from a queue")
    assert "Use Postgres\n" not in body and d_old not in body, "superseded decision must not be exported"
    assert "Mongo" not in body or "pgbouncer" in body


def test_plan_lists_open_items_as_tasks_by_priority(store, tmp_path):
    *_, p_hi, p_lo = _populate(store)
    store.resolve_pending(p_lo)
    store.add_pending("Benchmark the queue", priority="medium")

    export_workspace(store, MANIFEST, _cfg(tmp_path))

    fm, body = _frontmatter(tmp_path / "vault" / "acme" / "plan.md")
    assert fm["type"] == "plan" and fm["status"] == "proposed"
    assert "- [ ] [high] Rotate the signing certificate" in body
    assert "- [ ] [medium] Benchmark the queue" in body
    assert "Tidy the README" not in body
    assert body.index("Rotate the signing certificate") < body.index("Benchmark the queue")
    assert "proposal" in body.lower() and "decisions.md" in body


def test_context_describes_the_workspace_without_secrets(store, tmp_path):
    _populate(store)

    export_workspace(store, MANIFEST, _cfg(tmp_path))

    fm, body = _frontmatter(tmp_path / "vault" / "acme" / "context.md")
    assert fm["type"] == "context" and fm["display_name"] == "Acme Corp"
    assert "python, postgres" in body
    assert "azure" in body and "supabase" in body and "github" in body
    assert "src/app/parser.py" in body, "hot files belong in context"
    assert "Refactored the invoice exporter" in body, "last session summary belongs in context"
    assert "bot@acme.test" not in body, "no identity emails in the vault"
    assert "[[decisions]]" in body and "[[plan]]" in body


def test_fixes_note_lists_error_and_command(store, tmp_path):
    _populate(store)

    export_workspace(store, MANIFEST, _cfg(tmp_path))

    fm, body = _frontmatter(tmp_path / "vault" / "acme" / "fixes.md")
    assert fm["type"] == "fixes"
    assert "No module named 'yaml'" in body and "pip install pyyaml" in body


def test_session_notes_are_written_once_and_not_rewritten(store, tmp_path):
    _populate(store)
    cfg = _cfg(tmp_path)

    first = [p for p in export_workspace(store, MANIFEST, cfg) if "sessions" in p.parts]
    assert len(first) == 1
    fm, body = _frontmatter(first[0])
    assert fm["type"] == "session" and "Refactored the invoice exporter" in body
    assert "src/app/parser.py" in body
    first[0].write_text("hand edited", encoding="utf-8")

    second = [p for p in export_workspace(store, MANIFEST, cfg) if "sessions" in p.parts]

    assert second == [], "existing session notes are not rewritten"
    assert first[0].read_text(encoding="utf-8") == "hand edited"


def test_sessions_and_fixes_can_be_switched_off(store, tmp_path):
    _populate(store)

    written = export_workspace(store, MANIFEST, _cfg(tmp_path, export_sessions=False, export_fixes=False))

    names = {p.name for p in written}
    assert names == {"context.md", "decisions.md", "plan.md"}
    assert not (tmp_path / "vault" / "acme" / "sessions").exists()
    assert not (tmp_path / "vault" / "acme" / "fixes.md").exists()


def test_disabled_config_writes_nothing(store, tmp_path):
    _populate(store)
    assert export_workspace(store, MANIFEST, KnowledgeConfig(vault_dir=None)) == []
    assert not (tmp_path / "vault").exists()


def test_client_name_is_made_filesystem_safe(store, tmp_path):
    _populate(store)
    written = export_workspace(store, {**MANIFEST, "client": "acme/eu: prod"}, _cfg(tmp_path))
    assert written and written[0].parent.name == "acme-eu-prod" or written[0].parents[1].name == "acme-eu-prod"


def test_export_is_idempotent_for_the_rewritten_notes(store, tmp_path):
    _populate(store)
    cfg = _cfg(tmp_path)
    export_workspace(store, MANIFEST, cfg)
    before = {p.name: p.read_text(encoding="utf-8") for p in (tmp_path / "vault" / "acme").glob("*.md")}
    export_workspace(store, MANIFEST, cfg)
    after = {p.name: p.read_text(encoding="utf-8") for p in (tmp_path / "vault" / "acme").glob("*.md")}
    strip = lambda t: re.sub(r"^updated: .*$", "", t, flags=re.MULTILINE)
    assert {k: strip(v) for k, v in before.items()} == {k: strip(v) for k, v in after.items()}
