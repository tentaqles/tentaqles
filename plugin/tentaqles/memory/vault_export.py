"""Mirror a workspace's memory.db as Obsidian notes.

One folder per client under the vault dir:

    <vault>/<client>/context.md      what this workspace is, hot files, last session
    <vault>/<client>/decisions.md    active decisions with rationale (confirmed)
    <vault>/<client>/plan.md         open pending items as tasks (proposed)
    <vault>/<client>/fixes.md        error -> command that fixed it
    <vault>/<client>/sessions/<date>-<id>.md   one note per ended session

The first four are rewritten on every export; a session note is written once
and then left alone (it is history, and the human may annotate it). Every
note has YAML frontmatter -- type, client, display_name, status, updated,
generated_by -- so Obsidian Bases can filter on it, plus a comment saying the
file is generated. Everything here was redacted before it reached memory.db;
identity emails are deliberately not exported.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path

import yaml

from tentaqles.knowledge import KnowledgeConfig

MARKER = "<!-- generated by tentaqles from memory.db; edits to this file are overwritten on the next export -->"
_SAFE_RE = re.compile(r"[^A-Za-z0-9._-]+")


def safe_name(client: str) -> str:
    return _SAFE_RE.sub("-", client or "workspace").strip("-.") or "workspace"


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _note(front: dict, title: str, body_lines: list[str]) -> str:
    fm = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, default_flow_style=False).strip()
    return "---\n" + fm + "\n---\n" + MARKER + "\n\n# " + title + "\n\n" + "\n".join(body_lines).rstrip() + "\n"


def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return path


def _duration(seconds) -> str:
    try:
        s = int(seconds or 0)
    except (TypeError, ValueError):
        return ""
    if s < 60:
        return f"{s}s"
    if s < 3600:
        return f"{s // 60}m"
    return f"{s // 3600}h{(s % 3600) // 60:02d}m"


def export_workspace(store, manifest: dict, cfg: KnowledgeConfig) -> list[Path]:
    """Write the notes for one workspace. Returns the paths written this run."""
    if cfg.vault_dir is None:
        return []
    manifest = manifest or {}
    client = str(manifest.get("client") or "workspace")
    display = str(manifest.get("display_name") or client)
    client_dir = Path(cfg.vault_dir) / safe_name(client)
    updated = _now()

    def front(kind: str, status: str, **extra) -> dict:
        d = {"type": kind, "client": client, "display_name": display, "status": status, "updated": updated,
             "generated_by": "tentaqles"}
        d.update(extra)
        return d

    written: list[Path] = []
    written.append(_write(client_dir / "context.md", _context(store, manifest, client, display, front)))
    written.append(_write(client_dir / "decisions.md", _decisions(store, display, front)))
    written.append(_write(client_dir / "plan.md", _plan(store, display, front)))
    if cfg.export_fixes:
        written.append(_write(client_dir / "fixes.md", _fixes(store, display, front)))
    if cfg.export_sessions:
        written.extend(_sessions(store, display, front, client_dir / "sessions"))
    return written


def _context(store, manifest: dict, client: str, display: str, front) -> str:
    lines = [f"Client `{client}`."]
    stack = manifest.get("stack") or []
    if stack:
        lines.append("Stack: " + ", ".join(str(s) for s in stack) + ".")
    providers = []
    cloud = manifest.get("cloud") or {}
    if isinstance(cloud, dict) and cloud.get("provider") and cloud["provider"] != "none":
        sub = cloud.get("subscription_name")
        providers.append(f"cloud {cloud['provider']}" + (f" ({sub})" if sub else ""))
    db = manifest.get("database") or {}
    if isinstance(db, dict) and db.get("provider") and db["provider"] != "none":
        providers.append(f"database {db['provider']}")
    git = manifest.get("git") or {}
    if isinstance(git, dict) and (git.get("host") or git.get("provider")):
        user = git.get("user")
        providers.append(f"git {git.get('host') or git.get('provider')}" + (f" as {user}" if user else ""))
    if providers:
        lines.append("Providers: " + ", ".join(providers) + ".")

    last = store.get_last_session()
    if last:
        started = str(last.get("started_at") or "")[:10]
        lines += ["", f"## Last session ({started}, {_duration(last.get('duration_s'))})", "", str(last.get("summary") or "").strip()]

    hot = store.get_active_nodes(limit=5)
    if hot:
        lines += ["", "## Hot files", ""]
        for n in hot:
            lines.append(f"- `{n['node_id']}` (score {n['activity_score']}, {n['touch_count']} touches, {n['trend']})")

    stats = store.stats()
    fixes = len(store.get_recent_fixes(limit=1000))
    lines += ["", "## Memory",
              "",
              f"- sessions: {stats.get('sessions', 0)}",
              f"- decisions: {stats.get('decisions', 0)}",
              f"- open items: {len(store.get_open_pending())}",
              f"- fixes: {fixes}",
              "",
              "See [[decisions]], [[plan]] and [[fixes]]. Session notes are in `sessions/`."]
    return _note(front("context", "current"), display, lines)


def _decisions(store, display: str, front) -> str:
    rows = store.get_recent_decisions(days=365 * 100, status="active")
    lines = ["Confirmed choices, newest first. A superseded decision disappears from this list; "
             "its lineage stays in memory.db.", ""]
    if not rows:
        lines.append("_No decisions recorded yet._")
    for d in rows:
        lines.append(f"## {str(d['created_at'])[:10]} — {d['chosen']}")
        lines.append("")
        lines.append(f"- Rationale: {d['rationale']}")
        if d.get("rejected"):
            lines.append("- Rejected: " + "; ".join(str(r) for r in d["rejected"]))
        lines.append(f"- Confidence: {d.get('confidence', 'medium')}")
        lines.append(f"- id: `{d['id']}`")
        lines.append("")
    return _note(front("decisions", "confirmed", count=len(rows)), f"{display} — decisions", lines)


def _plan(store, display: str, front) -> str:
    rows = store.get_open_pending()
    lines = ["Open items are proposals: things noticed or suggested but not yet decided. "
             "When one is approved, record the decision (it then appears in [[decisions]] / decisions.md) "
             "and resolve the item here.", ""]
    if not rows:
        lines.append("_Nothing open._")
    for p in rows:
        lines.append(f"- [ ] [{p['priority']}] {p['description']} ({str(p['created_at'])[:10]}, `{p['id']}`)")
    return _note(front("plan", "proposed", count=len(rows)), f"{display} — plan", lines)


def _fixes(store, display: str, front) -> str:
    rows = store.get_recent_fixes(limit=200)
    lines = ["Errors and the command that made them go away, newest first.", ""]
    if not rows:
        lines.append("_No fixes recorded yet._")
    for f in rows:
        lines.append(f"- {str(f['created_at'])[:10]}: `{f['error']}` → `{f['command']}`")
    return _note(front("fixes", "recorded", count=len(rows)), f"{display} — fixes", lines)


def _sessions(store, display: str, front, sessions_dir: Path) -> list[Path]:
    written: list[Path] = []
    for s in store.list_sessions(limit=500):
        started = str(s.get("started_at") or "")
        path = sessions_dir / f"{started[:10] or 'undated'}-{s['id']}.md"
        if path.exists():
            continue
        lines = [str(s.get("summary") or "").strip() or "_No summary._"]
        files = store.session_files(s["id"], limit=10)
        if files:
            lines += ["", "## Files", ""]
            for f in files:
                lines.append(f"- `{f['node_id']}` ({f['action']}, {f['count']}x)")
        tags = s.get("tags") or []
        fm = front("session", "ended", session_id=s["id"], date=started[:10], duration=_duration(s.get("duration_s")))
        if tags:
            fm["tags"] = [str(t) for t in tags]
        written.append(_write(path, _note(fm, f"{display} — session {started[:10]}", lines)))
    return written
