// The PATH and environment layer of an identity whose manifest sets guard: v2 (PRD v2 §6.1
// step 2, §6.2 rows PATH and Environment; ADR-0007). It is built from the same compiled scope
// the hook judges by (policy.ScopeFor): an out-of-scope provider's CLI does not resolve by name
// on the identity PATH, and its variables are unset in the identity environment. Without the
// flag nothing here runs.

// MaskDirName is the per-identity folder, under the identity's folder in the tq home, that
// holds one stub per out-of-scope executable name (ADR-0007): it goes first on the identity
// PATH when a PATH folder that tq cannot drop (one shared with other tools) holds an
// out-of-scope CLI. A stub prints "<name>: command not found" and exits 127.
const MaskDirName = "path-mask"

// MaskDir is identity ws's mask folder: ~/.tentaqles/identities/<ws>/path-mask.
func MaskDir(ws string) string { return filepath.Join(paths.IdentitiesRoot(), ws, MaskDirName) }

// Layer is one identity's compiled PATH and environment layer.
type Layer struct {
	Identity string
	scope    *policy.Scope
	exes     map[string]string // out-of-scope executable name -> provider id
	maskDir  string
	ready    *bool // memoized MaskReady
}

// LayerFor is ws's layer, or nil when the v1 behaviour applies: no workspace, or a manifest
// without guard: v2. ws is a trusted workspace (resolve hands an untrusted one out apart).
func LayerFor(ws *resolve.Workspace) *Layer {
	if ws == nil || ws.Manifest == nil || !ws.Manifest.GuardV2() {
		return nil
	}
	s := policy.ScopeFor(ws.Name, ws.Manifest.Scope(), providers.MustLoad().All())
	return &Layer{Identity: ws.Name, scope: s, exes: s.OutOfScopeExecutables(), maskDir: MaskDir(ws.Name)}
}

// Scope is the compiled scope the layer was built from.
func (l *Layer) Scope() *policy.Scope { return l.scope }

// MaskDir is the layer's mask folder.
func (l *Layer) MaskDir() string { return l.maskDir }

// Masked is the sorted list of executable names the layer hides.
func (l *Layer) Masked() []string {
	out := make([]string, 0, len(l.exes))
	for n := range l.exes {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

// UnsetNames returns the variables, out of names, the identity environment unsets: an
// out-of-scope provider's variables no in-scope provider claims and the identity does not set
// itself (desired).
func (l *Layer) UnsetNames(names []string, desired map[string]string) []string {
	var out []string
	for _, n := range l.scope.OutOfScopeEnv(names) {
		if _, set := desired[n]; set {
			continue
		}
		if _, set := desired[envKey(n)]; set {
			continue
		}
		out = append(out, n)
	}
	return out
}

// stubSh and stubCmd are the two stub forms: a POSIX script (bash, zsh, Git Bash; and what a
// POSIX system runs) and, on Windows, a batch file (cmd.exe and PowerShell resolve names
// through PATHEXT and never run an extensionless file). The text is fixed words plus two
// validated names (the catalog's executable spelling and a workspace name): nothing a shell
// treats as syntax.
func stubSh(name, ws string) string {
	return "#!/bin/sh\n# Generated by tq (ADR-0007): " + name + " is outside the scope of identity " + ws + ". Do not edit.\n" +
		"echo \"" + name + ": command not found (outside the scope of identity " + ws + ")\" >&2\nexit 127\n"
}

func stubCmd(name, ws string) string {
	return "@echo off\r\nrem Generated by tq (ADR-0007): " + name + " is outside the scope of identity " + ws + ". Do not edit.\r\n" +
		"echo " + name + ": command not found, outside the scope of identity " + ws + " 1>&2\r\nexit /b 127\r\n"
}

// MaskFiles is the exact content of the mask folder, by file name.
func (l *Layer) MaskFiles() map[string][]byte {
	out := map[string][]byte{}
	if !workspace.NameRe.MatchString(l.Identity) {
		return out
	}
	for n := range l.exes {
		if !safeExeName(n) {
			continue
		}
		out[n] = []byte(stubSh(n, l.Identity))
		if runtime.GOOS == "windows" {
			out[n+".cmd"] = []byte(stubCmd(n, l.Identity))
		}
	}
	return out
}

// safeExeName is the catalog's executable spelling (providers.Match.Validate) again, as
// defence in depth for a name that becomes a file name and a word in a script.
func safeExeName(n string) bool {
	if n == "" || n[0] == '.' || n[0] == '-' {
		return false
	}
	for _, r := range n {
		if !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '.' || r == '_' || r == '+' || r == '-') {
			return false
		}
	}
	return true
}

// MaskReady reports whether the mask folder holds exactly the stubs MaskFiles names, each of
// its size: no file missing, none added. A folder that differs is never put on the PATH (a
// file added there would run in place of a real command); tq settings render writes it again.
func (l *Layer) MaskReady() bool {
	if l.ready != nil {
		return *l.ready
	}
	ok := l.maskReady()
	l.ready = &ok
	return ok
}

func (l *Layer) maskReady() bool {
	want := l.MaskFiles()
	es, err := os.ReadDir(l.maskDir)
	if err != nil || len(es) != len(want) || len(want) == 0 {
		return false
	}
	for _, e := range es {
		b, ok := want[e.Name()]
		if !ok || !e.Type().IsRegular() {
			return false
		}
		fi, err := e.Info()
		if err != nil || fi.Size() != int64(len(b)) {
			return false
		}
	}
	return true
}

// WriteMask brings the mask folder in line with MaskFiles: stale files removed, missing or
// different ones written (0700 on POSIX: run by the user only). It reports whether anything
// changed. Only human-only commands call it (tq allow, tq settings render): the folder is
// under the protected tq home.
func (l *Layer) WriteMask() (bool, error) {
	want := l.MaskFiles()
	if len(want) == 0 {
		return RemoveMask(l.Identity)
	}
	if err := os.MkdirAll(l.maskDir, 0o700); err != nil {
		return false, err
	}
	changed := false
	es, err := os.ReadDir(l.maskDir)
	if err != nil {
		return false, err
	}
	for _, e := range es {
		if _, ok := want[e.Name()]; !ok {
			if err := os.RemoveAll(filepath.Join(l.maskDir, e.Name())); err != nil {
				return changed, err
			}
			changed = true
		}
	}
	names := make([]string, 0, len(want))
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p := filepath.Join(l.maskDir, n)
		if cur, err := os.ReadFile(p); err == nil && bytes.Equal(cur, want[n]) {
			continue
		}
		tmp := p + ".tq.tmp"
		if err := os.WriteFile(tmp, want[n], 0o700); err != nil {
			return changed, err
		}
		if err := os.Rename(tmp, p); err != nil {
			_ = os.Remove(tmp)
			return changed, err
		}
		changed = true
	}
	l.ready = nil
	return changed, nil
}

// RemoveMask removes identity ws's mask folder (guard: v2 turned off, or nothing to mask). It
// reports whether there was one.
func RemoveMask(ws string) (bool, error) {
	if !workspace.NameRe.MatchString(ws) {
		return false, fmt.Errorf("invalid workspace name %q", ws)
	}
	dir := MaskDir(ws)
	if _, err := os.Lstat(dir); errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	return true, os.RemoveAll(dir)
}

// isMaskEntry reports whether an OS-spelled PATH entry is the layer's mask folder.
func (l *Layer) isMaskEntry(p string) bool {
	return p != "" && samePath(filepath.Clean(p), filepath.Clean(l.maskDir))
}

func samePath(a, b string) bool {
	if runtime.GOOS == "windows" {
		return strings.EqualFold(a, b)
	}
	return a == b
}
