// The mask folder (ADR-0007): one stub per out-of-scope executable name, in every spelling a
// shell resolves from PATH, so a name typed with its extension (aws.exe, vercel.ps1, aws.bat)
// or found through an edited PATHEXT lands on the stub too.
//
//   - an extensionless POSIX script (bash, zsh, Git Bash, and what a POSIX system runs);
//   - on Windows, name.exe and name.com: hard links to StubName, a copy (or hard link) of the tq
//     binary, which answers as a stub when run under a mask folder (StubMain). Being a program,
//     it returns to a batch file that calls it without `call`, which a .cmd stub would end;
//   - name.bat and name.cmd (batch), name.ps1 (PowerShell), name.vbs and name.js (Windows
//     Script Host), each printing the same line and exiting 127.

// StubName is the stub program in the mask folder that the .exe and .com stubs link to.
const StubName = "tq-stub.exe"

// StubSource is the program the stub is made from: the tq binary (DefaultStubSource). Tests
// that run the stub make it the test binary.
var StubSource = DefaultStubSource

// DefaultStubSource is the tq binary itself, never whatever program called the render: the
// running program when it is tq, else the tq on PATH. A program of another name (a harness, a
// test binary, a setup tool) is not a stub: its links would run it.
func DefaultStubSource() (string, error) {
	if exe, err := os.Executable(); err == nil && isTQBinary(exe) {
		return exe, nil
	}
	if p, err := exec.LookPath("tq"); err == nil && isTQBinary(p) {
		return filepath.Abs(p)
	}
	return "", fmt.Errorf("no tq binary to make the stub from: tq is not on PATH")
}

func isTQBinary(p string) bool {
	b := strings.ToLower(filepath.Base(p))
	return b == "tq" || b == "tq.exe"
}

// stubLine is the stub's message: fixed words and two validated names.
func stubLine(name, ws string) string {
	return name + ": command not found (outside the scope of identity " + ws + ")"
}

// MaskFiles is the content of the mask folder's script stubs, by file name (the .exe and .com
// links are maskLinks).
func (l *Layer) MaskFiles() map[string][]byte {
	out := map[string][]byte{}
	if !workspace.NameRe.MatchString(l.Identity) {
		return out
	}
	ws := l.Identity
	for n := range l.exes {
		if !safeExeName(n) {
			continue
		}
		msg := stubLine(n, ws)
		head := "Generated by tq (ADR-0007): " + n + " is outside the scope of identity " + ws + ". Do not edit."
		out[n] = []byte("#!/bin/sh\n# " + head + "\necho \"" + msg + "\" >&2\nexit 127\n")
		if runtime.GOOS != "windows" {
			continue
		}
		bat := "@echo off\r\nrem " + head + "\r\necho " + strings.ReplaceAll(strings.ReplaceAll(msg, "(", "^("), ")", "^)") + " 1>&2\r\nexit /b 127\r\n"
		out[n+".cmd"] = []byte(bat)
		out[n+".bat"] = []byte(bat)
		out[n+".ps1"] = []byte("# " + head + "\r\n[Console]::Error.WriteLine('" + msg + "')\r\nexit 127\r\n")
		out[n+".vbs"] = []byte("' " + head + "\r\nWScript.Echo \"" + msg + "\"\r\nWScript.Quit 127\r\n")
		out[n+".js"] = []byte("// " + head + "\r\nWScript.Echo(\"" + msg + "\");\r\nWScript.Quit(127);\r\n")
	}
	return out
}

// maskLinks are the .exe and .com names linked to the stub program (Windows only).
func (l *Layer) maskLinks() []string {
	if runtime.GOOS != "windows" || !workspace.NameRe.MatchString(l.Identity) {
		return nil
	}
	var out []string
	for n := range l.exes {
		if safeExeName(n) {
			out = append(out, n+".exe", n+".com")
		}
	}
	sort.Strings(out)
	return out
}

// safeExeName is the catalog's executable spelling (providers.Match.Validate) again, as
// defence in depth for a name that becomes a file name and a word in a script.
func safeExeName(n string) bool {
	if n == "" || n[0] == '.' || n[0] == '-' {
		return false
	}
	for _, r := range n {
		if !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '.' || r == '_' || r == '+' || r == '-') {
			return false
		}
	}
	return true
}

// MaskReady reports whether the mask folder holds exactly what tq writes: every script stub
// at its size, and on Windows the stub program with every .exe and .com link at its size; no
// file missing, none added. A folder that differs is never put on the PATH (a file added there
// would run in place of a real command). One directory read: it runs at every prompt the mask
// is wanted.
func (l *Layer) MaskReady() bool {
	if l.ready != nil {
		return *l.ready
	}
	ok := l.maskReady()
	l.ready = &ok
	return ok
}

func (l *Layer) maskReady() bool {
	want := l.MaskFiles()
	links := l.maskLinks()
	es, err := os.ReadDir(l.maskDir)
	if err != nil || len(want) == 0 {
		return false
	}
	n := len(want)
	if len(links) > 0 {
		n += len(links) + 1
	}
	if len(es) != n {
		return false
	}
	stubSize := int64(-1)
	sizes := map[string]int64{}
	for _, e := range es {
		if !e.Type().IsRegular() {
			return false
		}
		fi, err := e.Info()
		if err != nil {
			return false
		}
		sizes[e.Name()] = fi.Size()
		if e.Name() == StubName {
			stubSize = fi.Size()
		}
	}
	for name, b := range want {
		if s, ok := sizes[name]; !ok || s != int64(len(b)) {
			return false
		}
	}
	if len(links) > 0 {
		if stubSize <= 0 {
			return false
		}
		for _, name := range links {
			if s, ok := sizes[name]; !ok || s != stubSize {
				return false
			}
		}
	}
	return true
}

// WriteMask brings the mask folder in line with MaskFiles and the stub links: stale files
// removed, missing or different ones written (0700 on POSIX: run by the user only). It reports
// whether anything changed. Only human-only commands call it (tq allow, tq settings render):
// the folder is under the protected tq home.
func (l *Layer) WriteMask() (bool, error) {
	want := l.MaskFiles()
	if len(want) == 0 {
		return RemoveMask(l.Identity)
	}
	if err := os.MkdirAll(l.maskDir, 0o700); err != nil {
		return false, err
	}
	links := l.maskLinks()
	keep := map[string]bool{}
	for n := range want {
		keep[n] = true
	}
	for _, n := range links {
		keep[n] = true
	}
	if len(links) > 0 {
		keep[StubName] = true
	}
	changed := false
	es, err := os.ReadDir(l.maskDir)
	if err != nil {
		return false, err
	}
	for _, e := range es {
		if !keep[e.Name()] {
			if err := os.RemoveAll(filepath.Join(l.maskDir, e.Name())); err != nil {
				return changed, err
			}
			changed = true
		}
	}
	names := make([]string, 0, len(want))
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p := filepath.Join(l.maskDir, n)
		if cur, err := os.ReadFile(p); err == nil && bytes.Equal(cur, want[n]) {
			continue
		}
		if err := writeFileAtomic(p, want[n]); err != nil {
			return changed, err
		}
		changed = true
	}
	if len(links) > 0 {
		ch, err := l.writeStubLinks(links)
		if err != nil {
			return changed, err
		}
		changed = changed || ch
	}
	l.ready = nil
	return changed, nil
}

func writeFileAtomic(p string, b []byte) error {
	tmp := p + ".tq.tmp"
	if err := os.WriteFile(tmp, b, 0o700); err != nil {
		return err
	}
	if err := os.Rename(tmp, p); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

// writeStubLinks makes the stub program (a hard link to the tq binary, a copy when the two are
// on different volumes) and links every .exe and .com name to it. A link that already is the
// stub is left alone.
func (l *Layer) writeStubLinks(links []string) (bool, error) {
	src, err := StubSource()
	if err != nil {
		return false, fmt.Errorf("the stub program: %w", err)
	}
	stub := filepath.Join(l.maskDir, StubName)
	changed := false
	sfi, err := os.Stat(src)
	if err != nil {
		return false, err
	}
	if cur, err := os.Stat(stub); err != nil || !os.SameFile(cur, sfi) && cur.Size() != sfi.Size() {
		_ = os.Remove(stub)
		if err := os.Link(src, stub); err != nil {
			if err := copyFile(src, stub); err != nil {
				return false, fmt.Errorf("the stub program: %w", err)
			}
		}
		changed = true
	}
	st, err := os.Stat(stub)
	if err != nil {
		return changed, err
	}
	for _, n := range links {
		p := filepath.Join(l.maskDir, n)
		if cur, err := os.Stat(p); err == nil && os.SameFile(cur, st) {
			continue
		}
		_ = os.Remove(p)
		if err := os.Link(stub, p); err != nil {
			return changed, fmt.Errorf("link %s: %w", n, err)
		}
		changed = true
	}
	return changed, nil
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp := dst + ".tq.tmp"
	out, err := os.OpenFile(tmp, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o700)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		_ = os.Remove(tmp)
		return err
	}
	if err := out.Close(); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, dst)
}

// StubMain makes the tq binary answer as a stub when it runs from a mask folder
// (<tq home>/identities/<ws>/path-mask/<name>.exe): it prints "<name>: command not found
// (outside the scope of identity <ws>)" and returns 127. Every other run of tq returns false.
func StubMain(stderr io.Writer) (bool, int) {
	exe, err := os.Executable()
	if err != nil {
		return false, 0
	}
	dir := filepath.Dir(exe)
	if filepath.Base(dir) != MaskDirName || !strings.EqualFold(filepath.Base(filepath.Dir(filepath.Dir(dir))), "identities") {
		return false, 0
	}
	ws := filepath.Base(filepath.Dir(dir))
	name := strings.ToLower(filepath.Base(exe))
	name = strings.TrimSuffix(strings.TrimSuffix(name, ".exe"), ".com")
	if !workspace.NameRe.MatchString(ws) || !safeExeName(name) {
		ws, name = "", "command"
	}
	fmt.Fprintln(stderr, stubLine(name, ws))
	return true, 127
}
